function hasResults(){ return STP && STP.results && Object.keys(STP.results).length > 0; }
function randHex(n){ const a = new Uint8Array(n); crypto.getRandomValues(a); return [...a].map(x => x.toString(16).padStart(2, "0")).join(""); }
function genKeyId(){ return "ST-" + randHex(2).toUpperCase() + "-" + randHex(2).toUpperCase() + "-" + randHex(2).toUpperCase(); }
function genSecret(){ const abc = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"; const a = new Uint8Array(16); crypto.getRandomValues(a); return [...a].map(x => abc[x % abc.length]).join(""); }
function b64enc(buf){ return btoa(String.fromCharCode(...new Uint8Array(buf))); }
function b64dec(s){ return Uint8Array.from(atob(s), c => c.charCodeAt(0)); }
function download(name, text){
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([text], { type: "application/json" }));
  a.download = name; a.click(); setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}
async function deriveKey(secret, salt, iter){
  const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(secret), "PBKDF2", false, ["deriveKey"]);
  return crypto.subtle.deriveKey({ name: "PBKDF2", salt, iterations: iter, hash: "SHA-256" }, base, { name: "AES-GCM", length: 256 }, false, ["encrypt", "decrypt"]);
}
function profileObj(){
  return { app: "SmartTwin", version: 2, key_id: STP.key_id, created: new Date().toISOString(), results: STP.results, answers: STP.answers };
}
async function encryptVault(){
  if (!hasResults()) { msg("vault-msg", vm("need")); return; }
  try {
    if (!STP.key_id) {
      STP.key_id = genKeyId(); STP.secret = genSecret();
      document.getElementById("vault-keyid").textContent = "ID: " + STP.key_id;
      document.getElementById("vault-secret-show").textContent = STP.secret;
      document.getElementById("vault-key").hidden = false;
    }
    const salt = crypto.getRandomValues(new Uint8Array(16));
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const iter = 210000;
    const key = await deriveKey(STP.secret, salt, iter);
    const data = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(JSON.stringify(profileObj())));
    const vault = { app: "SmartTwin", type: "smarttwin-vault", version: 2, key_id: STP.key_id,
      kdf: { name: "PBKDF2", hash: "SHA-256", iterations: iter, salt: b64enc(salt) }, iv: b64enc(iv), data: b64enc(data) };
    download("smarttwin-boveda-" + STP.key_id + ".json", JSON.stringify(vault, null, 2));
    msg("vault-msg", "🔑 " + vm("keyShown") + "  ·  " + vm("vaultOk"));
  } catch (e) { msg("vault-msg", vm("vaultErr")); }
}
async function importVault(){
  const f = document.getElementById("vault-file").files[0];
  const secret = document.getElementById("vault-secret").value.trim();
  if (!f || !secret) { msg("vault-msg2", vm("importErr")); return; }
  try {
    const vault = JSON.parse(await f.text());
    if (vault.type !== "smarttwin-vault") throw new Error("type");
    const key = await deriveKey(secret, b64dec(vault.kdf.salt), vault.kdf.iterations);
    const plain = await crypto.subtle.decrypt({ name: "AES-GCM", iv: b64dec(vault.iv) }, key, b64dec(vault.data));
    const prof = JSON.parse(new TextDecoder().decode(plain));
    STP.results = prof.results || {}; STP.answers = prof.answers || {};
    STP.key_id = prof.key_id; STP.secret = secret;
    ["cog","eqsit","eqself","ipip","conn"].forEach(k => {
      const el = document.getElementById("st-" + k);
      if (el && STP.results[k]) el.textContent = rb("done");
    });
    msg("vault-msg2", vm("importOk") + " (" + STP.key_id + ")");
    if (window.onSTUpdate) window.onSTUpdate();
  } catch (e) { msg("vault-msg2", vm("importErr")); }
}
async function fingerprint(){
  const h = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(JSON.stringify(STP.answers || {})));
  return [...new Uint8Array(h)].map(x => x.toString(16).padStart(2, "0")).join("");
}
